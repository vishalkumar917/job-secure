"""Export the relational schema (tables + indexes) as SQL DDL from the SQLAlchemy models.

    python scripts/export_schema.py [sqlite|postgresql] > docs/schema.sql

Generating the DDL from the models keeps docs/schema.sql identical to what the
application actually creates.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))

from sqlalchemy.dialects import postgresql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import models  # noqa: E402,F401 - registers tables
from app.core.database import Base  # noqa: E402

DIALECTS = {"sqlite": sqlite.dialect(), "postgresql": postgresql.dialect()}


def main() -> None:
    name = sys.argv[1] if len(sys.argv) > 1 else "postgresql"
    dialect = DIALECTS[name]
    print(f"-- MemTrace relational schema ({name}). Generated by scripts/export_schema.py - do not edit by hand.\n")
    for table in Base.metadata.sorted_tables:
        print(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            print(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
        if table.indexes:
            print()


if __name__ == "__main__":
    main()
