import { Bot, RefreshCw, ShieldCheck, TriangleAlert } from "lucide-react";
import { useApi } from "../../hooks/useApi";
import { api } from "../../services/api";
import type { Finding } from "../../types";
import { Button, ErrorState, Loading, Mono, SeverityBadge } from "../ui";

function Section({ title, children, tone }: { title: string; children: React.ReactNode; tone?: "warn" }) {
  return (
    <div className={tone === "warn" ? "rounded-lg border border-sev-medium/40 bg-sev-medium/10 p-3" : ""}>
      <h4 className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted">{title}</h4>
      <div className="text-sm leading-relaxed text-ink-2">{children}</div>
    </div>
  );
}

/** Explainable-AI view of a single finding. Evidence and confidence are always taken from stored data. */
export function ExplanationPanel({ finding }: { finding: Finding }) {
  const { data, error, loading, reload, setData } = useApi(() => api.explanation(finding.id), [finding.id]);
  const regenerate = async () => setData(await api.explanation(finding.id, true));

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <SeverityBadge severity={finding.severity} />
        <span className="font-mono text-xs text-muted">{finding.rule_id}</span>
        {finding.attack_techniques.map((t) => (
          <a key={t} className="rounded bg-surface-3 px-1.5 py-0.5 font-mono text-[11px] text-ink-2 hover:text-accent"
            href={`https://attack.mitre.org/techniques/${t.replace(".", "/")}/`} target="_blank" rel="noreferrer">{t}</a>
        ))}
      </div>
      <p className="text-sm text-ink">{finding.finding}</p>
      {loading && !data ? <Loading label="Generating grounded explanation..." /> : error ? <ErrorState message={error} onRetry={reload} /> : data && (
        <>
          <div className="flex flex-wrap items-center gap-2 text-xs text-muted">
            <Bot className="h-4 w-4" /> Generated by <span className="font-medium text-ink-2">{data.provider}</span>{data.model && ` (${data.model})`}
            {data.grounded ? <span className="inline-flex items-center gap-1 text-good"><ShieldCheck className="h-3.5 w-3.5" />validated against evidence</span>
              : <span className="inline-flex items-center gap-1 text-sev-medium"><TriangleAlert className="h-3.5 w-3.5" />contains unverified statements</span>}
            <Button variant="ghost" onClick={regenerate} className="ml-auto"><RefreshCw className="h-3.5 w-3.5" />Regenerate</Button>
          </div>
          {(data.validation.warnings ?? []).length > 0 && <div className="text-xs text-sev-medium">{data.validation.warnings!.join(" ")}</div>}
          <Section title="What happened?">{data.content.what_happened}</Section>
          <Section title="Why is it suspicious?">{data.content.why_suspicious}</Section>
          <Section title="Evidence (forensic artifacts)">
            <ul className="space-y-1.5">
              {data.content.evidence.map((e, i) => (
                <li key={i} className="rounded-md border border-line bg-surface-2 px-2.5 py-1.5">
                  <div className="text-xs text-muted">{e.description} - <span className="font-mono">{e.source}</span>{e.ref && <span className="ml-1 font-mono">[{e.ref}]</span>}</div>
                  <Mono>{e.value}</Mono>
                </li>
              ))}
            </ul>
          </Section>
          <Section title="Confidence">
            <span className="font-semibold text-ink">{data.content.confidence.level}</span> ({data.content.confidence.value})
            <span className="block text-xs text-muted">{data.content.confidence.basis}</span>
          </Section>
          <Section title="Possible interpretation">{data.content.possible_interpretation}</Section>
          <Section title="What it does NOT prove" tone="warn">{data.content.does_not_prove}</Section>
          <Section title="Recommended next investigation">{data.content.recommended_next_steps}</Section>
        </>
      )}
    </div>
  );
}
